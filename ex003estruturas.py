frutas = ["maçã", "banana", "laranja"]
print(frutas[0])  # Acessa o primeiro elemento da lista
print(frutas[1])  # Acessa o segundo elemento da lista
print(frutas[2])  # Acessa o terceiro elemento da lista e assim por diante.

frutas.append("uva")  # Adiciona um novo elemento à lista
print(frutas)  # Imprime a lista atualizada

frutas.remove("banana")  # Remove um elemento da lista
print(frutas)  # Imprime a lista atualizada após a remoção

frutas.sort("")  # Ordena a lista em ordem alfabética
print(frutas)  # Imprime a lista ordenada

frutas.insert(1, "morango")  # Insere um elemento na posição especificada
print(frutas)  # Imprime a lista atualizada após a inserção

frutas.pop("")  # Remove o último elemento da lista
print(frutas)  # Imprime a lista atualizada após a remoção do último elemento